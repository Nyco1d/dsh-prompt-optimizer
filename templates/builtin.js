/** 用户自定义模板的合法性检查：id、name、system 三者必需 */
export function normalizeCustomMode(raw, index) {
  if (!raw || typeof raw !== 'object') return null;
  const system = typeof raw.system === 'string' ? raw.system.trim() : '';
  if (!system) return null;
  const id = typeof raw.id === 'string' && raw.id.trim()
    ? raw.id.trim()
    : `custom-${index + 1}`;
  const name = typeof raw.name === 'string' && raw.name.trim()
    ? raw.name.trim()
    : id;
  return {
    id,
    name,
    description: typeof raw.description === 'string' ? raw.description : '自定义模板',
    system,
    buildUser: wrapSource,
    custom: true,
  };
}
